export function pickRandomKent() {
  return KENT_NAMES[Math.floor(Math.random() * KENT_NAMES.length)];
}

export function pickEventLine(key) {
  const list = EVENT_DIALOGUES[key];
  if (!list || list.length === 0) return null;
  return list[Math.floor(Math.random() * list.length)];
}
